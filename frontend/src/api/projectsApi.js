import { API_BASE_URL } from "../config/api";

export const getMyProjects = (token) =>
  fetch(`${API_BASE_URL}/projects/me`, {
    headers: {
      Authorization: `Bearer ${token}`,
    },
  }).then(async (res) => {
    const data = await res.json();

    if (!res.ok) {
      return Promise.reject(data.message || `Error: ${res.status}`);
    }

    return data;
  });

